// Fixture: a repo where `bun run build` alone ships a BROKEN artifact. The
// generated API client (src/generated/client.ts) is committed STALE — it lacks
// the listUsers endpoint that api-spec.json declares. `bun run codegen`
// regenerates the client from the spec (adding listUsers); only `codegen` THEN
// `build` produces an artifact containing listUsers. Nothing in the README says
// so — the seeded project fact does. The engine must consume listUsers in
// src/client-usage.ts and run the correct pipeline. Zero dependencies.
import { buildFixture } from '../lib/deterministic-git.mjs';

// codegen: read api-spec.json, emit a client exporting one fn per endpoint.
const CODEGEN = `const spec = JSON.parse(await Bun.file('api-spec.json').text());
const fns = spec.endpoints
  .map((name) => \`export function \${name}(): string {\\n  return '\${name} result';\\n}\`)
  .join('\\n\\n');
const banner = '// GENERATED by codegen — do not edit by hand.\\n';
await Bun.write('src/generated/client.ts', banner + fns + '\\n');
console.log('codegen: wrote src/generated/client.ts for', spec.endpoints.join(', '));
`;

// check-artifact: the built bundle must contain the GENERATED listUsers body —
// the exact 'listUsers result' string codegen emits. Merely importing/calling
// listUsers from a stale client is not enough: without codegen the generated
// function (and its body string) is absent, so this fails until codegen ran
// before the build.
const CHECK = `import { existsSync } from 'node:fs';
if (!existsSync('dist/app.js')) {
  console.error('dist/app.js missing — run the build');
  process.exit(1);
}
const bundle = await Bun.file('dist/app.js').text();
if (!bundle.includes('listUsers result')) {
  console.error('artifact lacks the generated listUsers body — the client is stale (run codegen before build)');
  process.exit(1);
}
console.log('artifact OK: generated listUsers present');
`;

const FILES = {
  'package.json': `${JSON.stringify(
    {
      name: 'ts-lib-weird-build',
      version: '0.0.0',
      private: true,
      scripts: {
        codegen: 'bun run scripts/codegen.mjs',
        build: 'bun build src/client-usage.ts --outfile dist/app.js',
        'check-artifact': 'bun run scripts/check-artifact.mjs',
      },
    },
    null,
    2,
  )}\n`,
  'README.md': '# weird-build\n\nRun `bun run build` to build. (This README is deliberately incomplete.)\n',
  'api-spec.json': `${JSON.stringify({ endpoints: ['getUser', 'listUsers'] }, null, 2)}\n`,
  'scripts/codegen.mjs': CODEGEN,
  'scripts/check-artifact.mjs': CHECK,
  // STALE generated client: only getUser, missing listUsers. Committed so a plain
  // build bundles the stale version.
  'src/generated/client.ts': `// GENERATED by codegen — do not edit by hand.
export function getUser(): string {
  return 'getUser result';
}
`,
  // The consumer the engine edits to also call listUsers.
  'src/client-usage.ts': `import { getUser } from './generated/client';

export function main(): string {
  return getUser();
}
`,
};

export async function setup(dir) {
  await buildFixture(dir, FILES);
  return dir;
}
