/**
 * Presentation for the relay perf harness: console table + the baseline markdown.
 * Kept separate from measurement so the harness file stays focused on timing.
 */

export function printReport(machine, ttfd, fanout) {
  console.log(`\nRelay perf — ${machine.cpu} (${machine.cores}c), ${machine.runtime}, ${machine.platform}`);
  console.log(
    `TTFD  WS push p50=${ttfd.wsFirstDeltaMs.p50}ms p90=${ttfd.wsFirstDeltaMs.p90}ms | ` +
      `REST bootstrap p50=${ttfd.restBootstrapMs.p50}ms`,
  );
  console.log('N   events  thru/s   p50   p90   p99   cpu%   rssMB  frameB  dContentB  dOverheadB');
  for (const f of fanout) {
    console.log(
      `${String(f.n).padEnd(3)} ${String(f.events).padEnd(6)}  ${String(f.throughputPerSec).padEnd(7)} ` +
        `${String(f.latencyMs.p50).padEnd(5)} ${String(f.latencyMs.p90).padEnd(5)} ${String(f.latencyMs.p99).padEnd(5)} ` +
        `${String(f.cpuPct).padEnd(6)} ${String(f.rssMb).padEnd(6)} ${String(f.avgFrameBytes).padEnd(7)} ` +
        `${String(f.avgDeltaContentBytes).padEnd(10)} ${f.deltaEnvelopeOverheadBytes}`,
    );
  }
}

export function renderDoc(machine, ttfd, fanout, rounds) {
  const rows = fanout
    .map(
      (f) =>
        `| ${f.n} | ${f.events} | ${f.throughputPerSec} | ${f.latencyMs.p50} | ${f.latencyMs.p90} | ` +
        `${f.latencyMs.p99} | ${f.cpuPct} | ${f.rssMb} | ${f.avgFrameBytes} | ${f.avgDeltaContentBytes} | ` +
        `${f.deltaEnvelopeOverheadBytes} |`,
    )
    .join('\n');
  return `# Relay performance baseline (machine-as-cloud)

Generated by \`scripts/relay-perf-harness.mjs\` (\`bun run perf:relay -- --write\`). Regenerate
after any relay/fan-out change and compare — this is the ratchet reference, not a gate.

**Method.** Real module graph (SQLite + \`SessionsService\` + a simulated streaming provider) with
the real WS relay attached to a loopback HTTP server — the \`main.ts\` wiring minus the network
boundary. Latency = client receive time − event \`createdAt\` (append→wire→client), so it isolates
relay + serialization + loopback cost. **A real phone adds network RTT per hop on top of these.**
Deltas are coalesced server-side within the flush window before they reach the wire.

## Machine

- CPU: ${machine.cpu} (${machine.cores} cores)
- Memory: ${machine.memGb} GB
- Platform: ${machine.platform}, ${machine.runtime}
- Date: ${machine.date}

## Time-to-first-delta

| Path | p50 | p90 |
|---|---|---|
| WS push (first delta on the socket) | ${ttfd.wsFirstDeltaMs.p50} ms | ${ttfd.wsFirstDeltaMs.p90} ms |
| REST bootstrap (getEvents catch-up call) | ${ttfd.restBootstrapMs.p50} ms | ${ttfd.restBootstrapMs.p90} ms |

WS is a push: the relay fast-paths the first in-order delta so it lands almost immediately (later
deltas coalesce within the flush window). REST is a poll — a client without the socket pays the
bootstrap cost **once per poll**, so its effective first-delta latency is roughly \`poll_interval/2\`
on top of the bootstrap number above. The WS relay exists precisely to turn that poll into a push.

## Fan-out (N concurrent streaming sessions, ${rounds} steer rounds each)

| N | events | thru/s | p50 ms | p90 ms | p99 ms | cpu % | rss MB | frame B | delta content B | delta envelope B |
|---|---|---|---|---|---|---|---|---|---|---|
${rows}

- **thru/s** — total events delivered across all clients per wall second.
- **cpu %** — relay+service CPU (user+sys) as a fraction of wall time during the fan-out.
- **frame B** — average on-the-wire bytes per pushed frame.
- **delta content B / delta envelope B** — of a delta frame, how many bytes are the actual token
  text vs the fixed envelope (\`{"channel":"<id>","event":{"seq","type","payload","createdAt"}}\`).
  The envelope is the per-delta fixed cost; \`channel\` (the session id) repeats every frame because
  one socket multiplexes many sessions.

## Backpressure policy (measured + documented)

Per-connection outbound buffering is bounded (default 1 MB). A subscription whose socket cannot
drain is **dropped**, not buffered: the server sends one \`{ channel, behind: true }\` marker and the
client recovers by resubscribing from its last seen seq. One slow subscriber therefore cannot slow
or stall the others sharing the same session — pinned by the relay unit specs
(\`sessions.ws.spec.ts\` "drops an overflowing subscription with one behind marker",
\`sessions.ws-two-clients.spec.ts\` "fans live events to both subscribers; dropped client resumes
gap-free"). The real-service integration layer (reconnect storm, replay↔live race, daemon-restart
convergence) lives in \`sessions.ws.relay-e2e.spec.ts\`.

## Coverage note

The relay already bounds an initial \`since=0\` replay to a requested tail window (\`MAX_INITIAL_TAIL\`
in \`sessions.ws.ts\`), so a long-offline client reconnecting on a huge session no longer forces the
whole log into memory at once — the earlier "unbounded replay" concern is addressed in shipped code.

## Follow-up proposal (not changed — touches the frozen v1 contract)

- **Trim the per-delta envelope.** The tables above show a delta frame is dominated by its envelope
  (only a few bytes of token text under a fixed \`{"channel","event":{"seq","type","payload",
  "createdAt"}}\` wrapper). If profiling ever makes this matter (tiny tokens × huge fan-out),
  \`channel\` could become a subscription-scoped numeric id and \`createdAt\` could be dropped from
  deltas (the client orders by \`seq\`). Both change the frozen v1 relay envelope, so they belong
  behind an envelope version bump, not a silent edit.
`;
}
