/**
 * Opt-in, report-only Pi performance comparison.
 *
 * This makes real, billable model requests. It never runs unless explicitly
 * enabled:
 *   NUNCIO_PI_PERF=1 bun run perf:pi -- --trials 5
 *
 * The harness compares a fresh vanilla Pi SDK session with a fresh
 * PiAgentProvider session using the same model, prompt, and cwd. Results are
 * evidence, not a CI ratchet: no timing threshold can fail this command.
 */
import os from 'node:os';
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  realpathSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, '..');
const SERVER_NODE_MODULES = join(REPO_ROOT, 'apps/server/node_modules');

const ENABLED = process.env.NUNCIO_PI_PERF === '1' || process.argv.includes('--run');
const TRIALS = positiveInteger(argFlag('--trials') ?? argFlag('--rounds') ?? '5', 'trials');
const TIMEOUT_MS = positiveInteger(argFlag('--timeout-ms') ?? '120000', 'timeout-ms');
const PROMPT = argFlag('--prompt') ?? 'Reply with exactly the single word: pong';
const CWD = resolve(argFlag('--cwd') ?? REPO_ROOT);
const WRITE = process.argv.includes('--write');
const MODEL_OVERRIDE = argFlag('--model') ?? process.env.NUNCIO_PI_PERF_MODEL?.trim();

function argFlag(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function positiveInteger(raw, label) {
  const value = Number(raw);
  if (!Number.isInteger(value) || value <= 0) throw new Error(`--${label} must be a positive integer`);
  return value;
}

const round3 = (value) => Math.round(value * 1000) / 1000;

function summary(samples) {
  const sorted = [...samples].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  const median = sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
  const mean = samples.reduce((total, value) => total + value, 0) / samples.length;
  const variance = samples.reduce((total, value) => total + ((value - mean) ** 2), 0) / samples.length;
  return { medianMs: round3(median), cvPct: round3(mean === 0 ? 0 : (Math.sqrt(variance) / mean) * 100) };
}

function summarize(samples) {
  return {
    setup: summary(samples.map((sample) => sample.setupMs)),
    timeToFirstDelta: summary(samples.map((sample) => sample.timeToFirstDeltaMs)),
    postSetupTimeToFirstDelta: summary(samples.map((sample) => sample.postSetupTimeToFirstDeltaMs)),
    completion: summary(samples.map((sample) => sample.completionMs)),
  };
}

function renderReport(report) {
  const displayedCwd = report.cwd === REPO_ROOT ? '<repo>' : report.cwd;
  const rows = [];
  for (const arm of ['vanilla', 'provider']) {
    for (const [metric, values] of Object.entries(report.summary[arm])) {
      rows.push(`| ${arm} | ${metric} | ${values.medianMs} | ${values.cvPct} |`);
    }
  }
  return [
    '# Pi provider performance baseline',
    '',
    'Generated by `bun run perf:pi -- --run --trials 5 --write`. This is report-only',
    'evidence, not a timing gate; compare same-runner samples before adopting a threshold.',
    '',
    `- Date: ${report.date}`,
    `- SDK: ${report.sdkVersion}`,
    `- Model: ${report.model} (${report.modelSelection})`,
    `- Prompt: ${JSON.stringify(report.prompt)}`,
    `- Timeout: ${report.timeoutMs} ms`,
    `- Runtime: ${report.machine.runtime}`,
    `- Platform: ${report.machine.platform}`,
    `- CPU: ${report.machine.cpu} (${report.machine.cores} cores)`,
    `- Trials: ${report.trials} per arm after one warm-up`,
    `- Cwd: \`${displayedCwd}\``,
    '',
    '| Arm | Metric | Median ms | CV % |',
    '|---|---|---:|---:|',
    ...rows,
    '',
    '## Raw evidence',
    '',
    '```json',
    JSON.stringify({
      warmupEvidence: report.warmupEvidence,
      rawSamples: report.rawSamples,
      notes: report.notes,
    }, null, 2),
    '```',
    '',
  ].join('\n');
}

function validateSample(sample, label) {
  for (const key of ['setupMs', 'timeToFirstDeltaMs', 'postSetupTimeToFirstDeltaMs', 'completionMs']) {
    if (!Number.isFinite(sample[key]) || sample[key] < 0) throw new Error(`${label} produced invalid ${key}`);
  }
  if (sample.deltaCount < 1 || sample.outputChars < 1) throw new Error(`${label} emitted no text delta evidence`);
  if (sample.timeToFirstDeltaMs > sample.completionMs) throw new Error(`${label} completed before its first delta`);
}

function modelCost(model) {
  const input = Number(model.cost?.input);
  const output = Number(model.cost?.output);
  return (Number.isFinite(input) ? input : Number.MAX_SAFE_INTEGER / 2)
    + (Number.isFinite(output) ? output : Number.MAX_SAFE_INTEGER / 2);
}

function selectCheapestHaikuFirst(models) {
  const haiku = models.filter((model) => /haiku/i.test(`${model.provider}:${model.id}`));
  const pool = haiku.length ? haiku : models;
  return [...pool].sort((a, b) =>
    modelCost(a) - modelCost(b)
      || `${a.provider}:${a.id}`.localeCompare(`${b.provider}:${b.id}`),
  )[0];
}

export async function deadline(
  promise,
  timeoutMs,
  onTimeout,
  cleanupTimeoutMs = Math.min(10_000, Math.max(100, timeoutMs)),
) {
  let timer;
  const outcome = await Promise.race([
    promise.then(
      (value) => ({ type: 'resolved', value }),
      (error) => ({ type: 'rejected', error }),
    ),
    new Promise((resolveTimeout) => {
      timer = setTimeout(() => resolveTimeout({ type: 'timeout' }), timeoutMs);
    }),
  ]);
  clearTimeout(timer);

  if (outcome.type === 'resolved') return outcome.value;
  if (outcome.type === 'rejected') throw outcome.error;

  // Selecting timeout is irreversible. Abort may settle the measured promise,
  // but that settlement is cleanup evidence, never a successful sample.
  let cleanupTimer;
  const cleanup = (async () => {
    try {
      await onTimeout?.();
    } catch {
      // The timeout remains authoritative even if the abort acknowledgement fails.
    }
    await promise.catch(() => undefined);
  })();
  await Promise.race([
    cleanup,
    new Promise((resolveCleanup) => {
      cleanupTimer = setTimeout(resolveCleanup, cleanupTimeoutMs);
    }),
  ]);
  clearTimeout(cleanupTimer);
  throw new Error(`Pi performance sample timed out after ${timeoutMs}ms`);
}

function removeGeneratedSessionFile(file, agentDir, warnings) {
  if (!file || !existsSync(file)) return;
  const root = realpathSync(agentDir);
  const target = realpathSync(file);
  const rel = relative(root, target);
  if (!rel || rel.startsWith('..') || isAbsolute(rel) || !rel.endsWith('.jsonl')) {
    warnings.push(`left generated Pi session file in place because it was outside the agent dir: ${target}`);
    return;
  }
  unlinkSync(file);
}

async function loadRuntime() {
  await import(pathToFileURL(join(SERVER_NODE_MODULES, 'reflect-metadata/Reflect.js')).href);
  const pi = await import(pathToFileURL(join(
    SERVER_NODE_MODULES, '@earendil-works/pi-coding-agent/dist/index.js',
  )).href);
  const { Test } = await import(pathToFileURL(join(SERVER_NODE_MODULES, '@nestjs/testing/index.js')).href);
  const [{ DatabaseModule }, { SessionsPersistenceModule }, { SettingsModule }, { ContextModule }]
    = await Promise.all([
      import('../apps/server/src/db/database.module.ts'),
      import('../apps/server/src/sessions/sessions.persistence.module.ts'),
      import('../apps/server/src/settings/settings.module.ts'),
      import('../apps/server/src/context/context.module.ts'),
    ]);
  const [{ PiAgentProvider }, { SessionsRepository }, { NuncioContextRepository, NuncioContextService },
    { ExternalMemorySources }, { ExternalMemoriesService }, { createPiEngineModelRegistry }]
    = await Promise.all([
      import('../apps/server/src/agents/providers/pi-agent.provider.ts'),
      import('../apps/server/src/sessions/persistence/sessions.repository.ts'),
      import('../apps/server/src/agents/pi-engine/nuncio-context.ts'),
      import('../apps/server/src/agents/pi-engine/external-memory-sources.ts'),
      import('../apps/server/src/agents/pi-engine/external-memories.ts'),
      import('../apps/server/src/agents/pi-engine/model-registry.ts'),
    ]);
  return {
    pi, Test, DatabaseModule, SessionsPersistenceModule, SettingsModule, ContextModule,
    PiAgentProvider, SessionsRepository, NuncioContextRepository, NuncioContextService,
    ExternalMemorySources, ExternalMemoriesService, createPiEngineModelRegistry,
  };
}

async function main() {
  if (!ENABLED) {
    console.log('Pi perf skipped: set NUNCIO_PI_PERF=1 or pass --run to allow real, billable prompts.');
    return;
  }
  const runtime = await loadRuntime();
  const agentDir = resolve(process.env.PI_CODING_AGENT_DIR?.trim()
    || process.env.PI_AGENT_DIR?.trim()
    || runtime.pi.getAgentDir());
  if (!existsSync(join(agentDir, 'auth.json'))) throw new Error(`Pi auth is missing from ${agentDir}`);

  const registrySettings = {
    resolve: (key) => key === 'NUNCIO_PI_MODELS_PATH' ? process.env.NUNCIO_PI_MODELS_PATH : undefined,
  };
  const initialRegistry = runtime.createPiEngineModelRegistry(runtime.pi, agentDir, registrySettings).modelRegistry;
  const availableModels = initialRegistry.getAvailable();
  const selected = MODEL_OVERRIDE
    ? availableModels.find((model) => `${model.provider}:${model.id}` === MODEL_OVERRIDE)
    : selectCheapestHaikuFirst(availableModels);
  if (!selected) {
    throw new Error(MODEL_OVERRIDE
      ? `Pi model override ${MODEL_OVERRIDE} is not in the authenticated registry`
      : 'Pi model registry contains no authenticated model');
  }
  const modelKey = `${selected.provider}:${selected.id}`;
  const warnings = [];

  const priorDataDir = process.env.NUNCIO_DATA_DIR;
  const dataDir = mkdtempSync(join(tmpdir(), 'nuncio-pi-perf-'));
  process.env.NUNCIO_DATA_DIR = dataDir;
  let module;
  try {
    module = await runtime.Test.createTestingModule({
      imports: [runtime.DatabaseModule, runtime.SessionsPersistenceModule, runtime.SettingsModule, runtime.ContextModule],
      providers: [
        runtime.PiAgentProvider,
        runtime.NuncioContextRepository,
        runtime.NuncioContextService,
        runtime.ExternalMemorySources,
        runtime.ExternalMemoriesService,
      ],
    }).compile();
    const provider = module.get(runtime.PiAgentProvider);
    const sessions = module.get(runtime.SessionsRepository);

    let setupRecorder;
    const originalCreatePiSession = provider.createPiSession;
    if (typeof originalCreatePiSession !== 'function') throw new Error('Pi provider setup instrumentation is unavailable');
    provider.createPiSession = async function (...args) {
      const startedAt = performance.now();
      try {
        return await originalCreatePiSession.apply(this, args);
      } finally {
        setupRecorder?.({ startedAt, endedAt: performance.now() });
      }
    };

    const runVanilla = async () => {
      const startedAt = performance.now();
      const { authStorage, modelRegistry } = runtime.createPiEngineModelRegistry(
        runtime.pi, agentDir, registrySettings,
      );
      const model = modelRegistry.find(selected.provider, selected.id);
      if (!model) throw new Error(`Vanilla registry cannot resolve ${modelKey}`);
      const created = await runtime.pi.createAgentSession({ cwd: CWD, agentDir, authStorage, modelRegistry, model });
      const setupEndedAt = performance.now();
      const session = created.session;
      let firstDeltaAt;
      let deltaCount = 0;
      let outputChars = 0;
      const unsubscribe = session.subscribe((event) => {
        const inner = event.type === 'message_update' ? event.assistantMessageEvent : undefined;
        if (inner?.type !== 'text_delta' || !inner.delta) return;
        firstDeltaAt ??= performance.now();
        deltaCount += 1;
        outputChars += inner.delta.length;
      });
      try {
        await deadline(session.prompt(PROMPT), TIMEOUT_MS, () => session.abort());
        const endedAt = performance.now();
        const sample = makeSample(startedAt, setupEndedAt, firstDeltaAt, endedAt, deltaCount, outputChars);
        validateSample(sample, 'vanilla Pi');
        return sample;
      } finally {
        unsubscribe();
        session.dispose?.();
        removeGeneratedSessionFile(session.sessionFile, agentDir, warnings);
      }
    };

    const runProvider = async () => {
      const created = sessions.create({
        prompt: PROMPT,
        provider: 'pi',
        model: modelKey,
        workspace: CWD,
        projectPath: CWD,
      });
      const startedAt = performance.now();
      let setupWindow;
      setupRecorder = (window) => { setupWindow = window; };
      let firstDeltaAt;
      let deltaCount = 0;
      let outputChars = 0;
      const runPromise = provider.run(created.id, PROMPT, {
        cwd: CWD,
        model: modelKey,
        emit: (event) => {
          if (event.type !== 'assistant_delta') return;
          if (!Number.isInteger(event.seq) || event.seq < 1) throw new Error('Pi provider emitted a non-durable delta');
          firstDeltaAt ??= performance.now();
          deltaCount += 1;
          outputChars += String(event.payload?.delta ?? '').length;
        },
      });
      try {
        await deadline(runPromise, TIMEOUT_MS, () => provider.interrupt(created.id));
        const endedAt = performance.now();
        if (!setupWindow) throw new Error('Pi provider produced no setup timing evidence');
        const sample = makeSample(
          startedAt, setupWindow.endedAt, firstDeltaAt, endedAt, deltaCount, outputChars,
          setupWindow.endedAt - setupWindow.startedAt,
        );
        validateSample(sample, 'PiAgentProvider');
        return sample;
      } finally {
        setupRecorder = undefined;
        const threadId = sessions.findById(created.id)?.providerThreadId;
        provider.dispose(created.id);
        removeGeneratedSessionFile(threadId, agentDir, warnings);
      }
    };

    const runners = { vanilla: runVanilla, provider: runProvider };
    const warmup = {};
    for (const name of ['vanilla', 'provider']) warmup[name] = await runners[name]();
    const trials = [];
    for (let index = 0; index < TRIALS; index += 1) {
      const order = index % 2 === 0 ? ['provider', 'vanilla'] : ['vanilla', 'provider'];
      const samples = {};
      for (const name of order) samples[name] = await runners[name]();
      trials.push({ trial: index + 1, order, ...samples });
    }

    const vanilla = trials.map((trial) => trial.vanilla);
    const providerSamples = trials.map((trial) => trial.provider);
    const report = {
      kind: 'report-only',
      thresholds: null,
      date: new Date().toISOString(),
      sdkVersion: JSON.parse(readFileSync(join(
        SERVER_NODE_MODULES,
        '@earendil-works/pi-coding-agent/package.json',
      ), 'utf8')).version,
      model: modelKey,
      modelSelection: MODEL_OVERRIDE
        ? 'explicit override'
        : /haiku/i.test(modelKey) ? 'cheapest available Haiku' : 'cheapest available fallback',
      prompt: PROMPT,
      cwd: CWD,
      trials: TRIALS,
      timeoutMs: TIMEOUT_MS,
      machine: {
        cpu: os.cpus()[0]?.model ?? 'unknown',
        cores: os.cpus().length,
        platform: `${process.platform}/${process.arch}`,
        runtime: `bun ${process.versions.bun}`,
      },
      warmupEvidence: warmup,
      summary: { vanilla: summarize(vanilla), provider: summarize(providerSamples) },
      rawSamples: trials,
      notes: [
        'Warm-up evidence is reported separately and excluded from summary statistics.',
        'setupMs covers fresh session construction; TTFD and completion include setup.',
        'CV is population standard deviation divided by mean; timings never gate success.',
        ...warnings,
      ],
    };
    console.log(JSON.stringify(report, null, 2));
    if (WRITE) {
      const output = join(REPO_ROOT, 'docs', 'pi-provider-performance-baseline.md');
      writeFileSync(output, renderReport(report));
      console.log(`wrote ${output}`);
    }
  } finally {
    await module?.close();
    rmSync(dataDir, { recursive: true, force: true });
    if (priorDataDir === undefined) delete process.env.NUNCIO_DATA_DIR;
    else process.env.NUNCIO_DATA_DIR = priorDataDir;
  }
}

function makeSample(startedAt, setupEndedAt, firstDeltaAt, endedAt, deltaCount, outputChars, setupOverride) {
  if (firstDeltaAt === undefined) throw new Error('Pi sample completed without a text delta');
  return {
    setupMs: round3(setupOverride ?? (setupEndedAt - startedAt)),
    timeToFirstDeltaMs: round3(firstDeltaAt - startedAt),
    postSetupTimeToFirstDeltaMs: round3(firstDeltaAt - setupEndedAt),
    completionMs: round3(endedAt - startedAt),
    deltaCount,
    outputChars,
  };
}

if (import.meta.main) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.stack ?? error.message : String(error));
    process.exitCode = 1;
  });
}
